window.WOORDSPRINT_CATEGORIES = [];
window.WOORDSPRINT_ITEMS = [];

let currentCategory = null;
let itemIndex = 0;

window.WOORDSPRINT_DATA
  .split(/\r?\n/)
  .map((line) => line.trim())
  .filter(Boolean)
  .forEach((line) => {
    if (line.startsWith("##")) {
      const [id, label, description] = line.slice(2).split("|");
      currentCategory = { id, label, description };
      window.WOORDSPRINT_CATEGORIES.push(currentCategory);
      return;
    }

    const [term, answer, definition] = line.split(";");
    if (!currentCategory || !term || !answer || !definition) return;
    window.WOORDSPRINT_ITEMS.push({
      id: `w${++itemIndex}`,
      category: currentCategory.id,
      term: term.trim(),
      answer: answer.trim(),
      definition: definition.trim()
    });
  });
